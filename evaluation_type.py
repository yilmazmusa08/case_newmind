import pandas as pd

df_pred = pd.read_csv("/content/opinion_pred_bart.csv")
df_true = pd.read_csv("/content/opinions.csv")

df_true["pred"] = df_pred['predictions'].apply(lambda x: eval(x).get('labels', [])[0] if pd.notnull(x) else None)

from sklearn.metrics import confusion_matrix
import seaborn as sns
import matplotlib.pyplot as plt

# Assuming 'df_true' is your DataFrame with true labels and 'df_pred' is your DataFrame with predicted labels
# Replace 'your_dataframe' with your actual DataFrame names

# Make true labels lowercase
df_true['type'] = df_true['type'].str.lower()

true_labels = df_true['type']
predicted_labels = df_true['pred']

# Calculate confusion matrix
conf_matrix = confusion_matrix(true_labels, predicted_labels, labels=df_true['type'].unique())

# Plot confusion matrix using seaborn heatmap
plt.figure(figsize=(8, 6))
sns.heatmap(conf_matrix, annot=True, fmt="d", cmap="Blues", xticklabels=df_true['type'].unique(), yticklabels=df_true['type'].unique())
plt.xlabel('Predicted')
plt.ylabel('True')
plt.title('Confusion Matrix')
plt.show()

from sklearn.metrics import precision_recall_fscore_support

# Calculate precision, recall, and F1-score for each label separately
label_metrics = {}

for label in df_true['type'].unique():
    mask = true_labels == label
    label_true = true_labels[mask]
    label_pred = predicted_labels[mask]

    # Calculate precision, recall, and F1-score
    metrics = precision_recall_fscore_support(label_true, label_pred, average='weighted')
    label_metrics[label] = {
        'precision': metrics[0],
        'recall': metrics[1],
        'f1-score': metrics[2]
    }

# Print metrics for each label
for label, metrics in label_metrics.items():
    print(f"Metrics for label '{label}':")
    print(f"Precision: {metrics['precision']}")
    print(f"Recall: {metrics['recall']}")
    print(f"F1-score: {metrics['f1-score']}")
    print()